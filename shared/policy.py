"""AgentGuard deterministic policy engine (no LLM). Spec: README.md sections 5.1-5.3, 6.

policy.json (written by Onboarding, re-read on every call):
    {
      "business": str,
      "company_domains": [str],
      "default_by_risk": {"read": "allow", "write": "ask", "destructive": "ask"},
      "rules": [   # top to bottom, first match wins; specific rules first, catch-all last
        {
          "id": str,
          "category": "payment" | "email_send" | "read" | "bulk_export",
          "effect": "allow" | "deny" | "ask",
          "when": {<operator>: <value>, ...},   # all conditions must hold; {} = always
          "explain": str                        # optional, plain-language description
        }
      ]
    }
    Supported `when` operators (any other operator -> deny):
      amount_usd_lte:      number              payment amount in USD <= value
      daily_total_usd_lte: number              today's total + this payment (USD) <= value
      all_recipients_in:   [domain] | "company_domains"   every recipient's domain is listed
      any_recipient_in:    [domain] | "company_domains"   at least one recipient's domain is listed
    TODO: rules are populated by Onboarding or by tests.

registry.json (generated by classify_tools.py from list_tools, then reviewed):
    {
      "<tool_name>": {
        "category": "payment" | "email_send" | "read" | "bulk_export",
        "risk": "read" | "write" | "destructive",
        "amount_field": str,             # payment tools
        "amount_unit": "cents" | "usd",  # payment tools
        "recipient_fields": [str],       # email_send tools, e.g. ["to", "cc", "bcc"]
        "source": "pack" | "claude" | "reviewed"
      }
    }
    TODO: populate from the real list_tools output.

Fail-closed:
    - A tool missing from registry.json is treated as risk "write" (-> ask, never allow).
      The Gateway should also send it for classification (see is_registered()).
    - An unparseable amount, malformed recipients, or any exception -> deny.
"""
from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

BASE_DIR = Path(__file__).resolve().parent
POLICY_PATH = BASE_DIR / "policy.json"
REGISTRY_PATH = BASE_DIR / "registry.json"

OPERATORS = {"amount_usd_lte", "daily_total_usd_lte", "all_recipients_in", "any_recipient_in"}
UNIT_DIVISORS = {"cents": 100, "usd": 1}
EFFECTS = ("allow", "deny", "ask")
RISKS = ("read", "write", "destructive")
UNREGISTERED_TOOL = {"category": None, "risk": "write"}

AGENT_MESSAGES = {
    "allow": "Allowed by policy.",
    "ask": "This action requires the owner's approval.",
    "deny": "This action is not allowed by the business policy.",
}


@dataclass
class Decision:
    effect: Literal["allow", "deny", "ask"]
    rule_id: str | None      # which rule decided; None = default
    reason: str              # for the dashboard and Slack
    reason_for_agent: str    # returned to the agent when blocked


def load_policy() -> dict:
    """Reads policy.json from disk on every call (no caching)."""
    with open(POLICY_PATH, encoding="utf-8") as f:
        return json.load(f)


def load_registry() -> dict:
    with open(REGISTRY_PATH, encoding="utf-8") as f:
        return json.load(f)


def is_registered(tool_name: str, registry: dict) -> bool:
    return tool_name in registry


def tool_entry(tool_name: str, registry: dict) -> dict:
    """The registry entry, or the fail-closed default for an unregistered tool."""
    return registry.get(tool_name, UNREGISTERED_TOOL)


def normalize_amount_usd(raw, unit: str) -> float:
    """Converts a raw amount to USD. Raises ValueError/TypeError if invalid."""
    if unit not in UNIT_DIVISORS or raw is None or isinstance(raw, bool):
        raise ValueError("invalid amount")
    value = float(raw)
    if not math.isfinite(value) or value < 0:
        raise ValueError("invalid amount")
    return value / UNIT_DIVISORS[unit]


def amount_usd_for(tool_name: str, args: dict, registry: dict) -> float | None:
    """USD amount of a payment call, or None if not a payment / not parseable."""
    tool = tool_entry(tool_name, registry)
    if tool.get("category") != "payment":
        return None
    try:
        return normalize_amount_usd(args.get(tool["amount_field"]), tool["amount_unit"])
    except (KeyError, ValueError, TypeError):
        return None


def collect_recipients(args: dict, fields: list[str]) -> list[str]:
    """Lowercased recipient addresses from the given fields (str, comma-separated str, or list)."""
    recipients = []
    for field in fields:
        value = args.get(field)
        if value is None:
            continue
        items = [value] if isinstance(value, str) else value
        for item in items:
            if not isinstance(item, str):
                raise ValueError("invalid recipient")
            for addr in item.split(","):
                addr = addr.strip().lower()
                if addr:
                    recipients.append(addr)
    return recipients


def _domain(addr: str) -> str:
    local, sep, domain = addr.rpartition("@")
    if not sep or not local or not domain:
        raise ValueError("invalid recipient")
    return domain


def _domain_list(value, policy: dict) -> set[str]:
    """A list of domains, or the name of a top-level policy list (e.g. "company_domains")."""
    if isinstance(value, str):
        value = policy[value]
    if not isinstance(value, list) or not all(isinstance(d, str) for d in value):
        raise ValueError("invalid domain list")
    return {d.strip().lower() for d in value}


def _matches(when: dict, policy: dict, amount_usd, recipients, db) -> bool:
    for op, value in when.items():
        if op not in OPERATORS:
            raise ValueError(f"unsupported operator: {op}")
        if op == "amount_usd_lte":
            if amount_usd is None or amount_usd > float(value):
                return False
        elif op == "daily_total_usd_lte":
            if amount_usd is None or db.daily_total_usd() + amount_usd > float(value):
                return False
        else:
            # Exact match on the part after "@", so "x.com.evil.io" does not match "x.com"
            if not recipients:
                return False
            domains = _domain_list(value, policy)
            check = all if op == "all_recipients_in" else any
            if not check(_domain(r) in domains for r in recipients):
                return False
    return True


def _evaluate(tool_name: str, args: dict, policy: dict, registry: dict, db) -> Decision:
    if not isinstance(args, dict):
        raise ValueError("arguments must be an object")
    registered = is_registered(tool_name, registry)
    tool = tool_entry(tool_name, registry)
    category = tool.get("category")

    amount_usd = None
    if category == "payment":
        amount_usd = amount_usd_for(tool_name, args, registry)
        if amount_usd is None:
            return Decision("deny", None, "Invalid or missing payment amount",
                            "The payment amount could not be read. " + AGENT_MESSAGES["deny"])

    recipients = None
    if category == "email_send":
        recipients = collect_recipients(args, tool["recipient_fields"])
        if not recipients:
            return Decision("deny", None, "Email has no recipients",
                            "The email has no recipients. " + AGENT_MESSAGES["deny"])
        for r in recipients:
            _domain(r)  # validates address format; raises -> deny

    for rule in policy["rules"]:
        if rule["category"] != category:
            continue
        if _matches(rule.get("when", {}), policy, amount_usd, recipients, db):
            effect = rule["effect"]
            if effect not in EFFECTS:
                raise ValueError(f"invalid effect: {effect}")
            reason = rule.get("explain") or f"Matched rule {rule['id']}"
            return Decision(effect, rule["id"], reason, f"{AGENT_MESSAGES[effect]} {reason}")

    # No rule matched: default by risk. Unregistered or unknown risk counts as "write".
    risk = tool.get("risk")
    if risk not in RISKS:
        risk = "write"
    effect = policy["default_by_risk"][risk]
    if effect not in EFFECTS:
        raise ValueError(f"invalid default effect: {effect}")
    if registered:
        reason = f"No rule matched; default for risk '{risk}'"
    else:
        reason = "Tool not in registry; treated as write"
    return Decision(effect, None, reason, AGENT_MESSAGES[effect])


def evaluate(tool_name: str, args: dict, policy: dict, registry: dict, db=None) -> Decision:
    """Deterministic evaluation. Any exception results in deny.

    `db` must provide daily_total_usd() -> float. Defaults to the `store` module.
    """
    try:
        if db is None:
            from . import store as db
        return _evaluate(tool_name, args, policy, registry, db)
    except Exception as e:
        return Decision("deny", None, f"Check failed: {type(e).__name__}: {e}",
                        "Policy check failed. " + AGENT_MESSAGES["deny"])
